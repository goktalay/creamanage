    async def test_roller(self):
        r = await self.yon.post("/api/dosyalar", data=self._form(b"G28\n", "r.gcode")); d = (await r.json())["dosya"]
        # Gözetmen: görür ve indirir, ekleyemez/değiştiremez/gönderemez
        r = await self.goz.get(f"/api/dosyalar/{d['id']}/indir"); self.assertEqual(r.status, 200); self.assertEqual(await r.read(), b"G28\n")
        self.assertIn("dosya_indirdi", [g["eylem"] for g in self.vt.denetim_listesi()])
        r = await self.goz.post("/api/dosyalar", data=self._form(b"G28\n", "g.gcode")); self.assertEqual(r.status, 403)
        r = await self.goz.put(f"/api/dosyalar/{d['id']}", json={"durum": "pasif"}); self.assertEqual(r.status, 403)
        r = await self.goz.post(f"/api/dosyalar/{d['id']}/gonder", json={"yazici_id": self.yid}); self.assertEqual(r.status, 403)
        # Silme yalnız sistem yöneticisi
        r = await self.yon.delete(f"/api/dosyalar/{d['id']}"); self.assertEqual(r.status, 403)
        r = await self.admin.delete(f"/api/dosyalar/{d['id']}"); self.assertEqual(r.status, 200)
        self.assertEqual(self.vt.dosyalar(), [])
        # Gözetmen yazıcı adını değiştirebilir, başka alanı değiştiremez
        r = await self.goz.put(f"/api/yazicilar/{self.yid}/ad", json={"ad": "Hat-1 / 07"}); self.assertEqual(r.status, 200, await r.text())
        self.assertEqual(self.vt.yazici(self.yid)["ad"], "Hat-1 / 07"); self.assertEqual(self.filo.kayitlar[self.yid]["ad"], "Hat-1 / 07")
        self.assertIn("yazici_adlandirdi", [g["eylem"] for g in self.vt.denetim_listesi()])
        r = await self.goz.put(f"/api/yazicilar/{self.yid}/ad", json={"ad": "   "}); self.assertEqual(r.status, 400)
        r = await self.goz.put(f"/api/yazicilar/{self.yid}", json={"ad": "X"}); self.assertEqual(r.status, 403)
        r = await self.goz.put("/api/yazicilar/999/ad", json={"ad": "X"}); self.assertEqual(r.status, 404)


